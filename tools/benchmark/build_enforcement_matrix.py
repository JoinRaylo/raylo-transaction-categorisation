def main() -> None:
    binding = ReleaseBinding(**eval_protection.PINNED_BINDING)
    entries = tuple(
        ConsumerCoverage(
            consumer=consumer,
            kind=kind,
            enforcement=enforcement,
            boundary=boundary,
            evidence=evidence,
        )
        for consumer, kind, enforcement, boundary, evidence in sorted(
            ENTRIES, key=lambda e: e[0]
        )
    )
    matrix = CoverageMatrix(release=binding, entries=entries)
    receipt = EnforcementReceipt(
        release=binding,
        matrix_sha256=matrix.matrix_sha256,
        checks=tuple(CHECKS),
        limitations=tuple(LIMITATIONS),
    )
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    matrix_path = OUT_DIR / "coverage-matrix.json"
    receipt_path = OUT_DIR / "enforcement-receipt.json"
    matrix_path.write_text(matrix.model_dump_json(indent=2) + "\n", encoding="utf-8")
    receipt_path.write_text(receipt.model_dump_json(indent=2) + "\n", encoding="utf-8")
    print(f"matrix: {len(entries)} consumers, sha {matrix.matrix_sha256}")
    print(f"receipt: sha {receipt.receipt_sha256} -> {receipt_path}")


if __name__ == "__main__":
    main()
